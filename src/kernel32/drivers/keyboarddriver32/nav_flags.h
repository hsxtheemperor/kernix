// nav_flags.h
#ifndef NAV_FLAGS_H
#define NAV_FLAGS_H

#define NAV_UP        (1 << 0)  // 0000 0001
#define NAV_DOWN      (1 << 1)  // 0000 0010
#define NAV_LEFT      (1 << 2)  // 0000 0100
#define NAV_RIGHT     (1 << 3)  // 0000 1000

#define NAV_HOME      (1 << 4)  // 0001 0000
#define NAV_END       (1 << 5)  // 0010 0000
#define NAV_PGUP      (1 << 6)  // 0100 0000
#define NAV_PGDOWN    (1 << 7)  // 1000 0000

#endif
